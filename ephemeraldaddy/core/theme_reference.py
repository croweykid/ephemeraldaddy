THEME_ENTRY_KEYS = frozenset(
    {
        "label",
        "family",
        *WEIGHTED_THEME_PROPERTIES,
        *THEME_METADATA_LIST_PROPERTIES,
        "notes",
        "default_weight",
        "weight_overrides",
    }
)


def theme_item_weight(theme_key: str, property_name: str, item: Any) -> float:
    """Return the item's thematic membership weight.

    Listed items default to 1.0 (or the theme's future custom default).
    Unlisted items return 0.0. ``weight_overrides`` is intentionally sparse.
    """

    if property_name not in WEIGHTED_THEME_PROPERTIES:
        raise KeyError(f"{property_name!r} is not a weighted theme property")

    theme = THEMES[theme_key]
    if item not in theme[property_name]:
        return 0.0

    return float(
        theme["weight_overrides"]
        .get(property_name, {})
        .get(item, theme["default_weight"])
    )


def themes_in_family(family_key: str) -> dict[str, dict[str, Any]]:
    """Return theme entries assigned to one organizational family."""

    if family_key not in THEME_FAMILIES:
        raise KeyError(f"Unknown theme family: {family_key!r}")
    return {
        theme_key: theme
        for theme_key, theme in THEMES.items()
        if theme["family"] == family_key
    }


def validate_theme_reference() -> None:
    """Raise ValueError if the reference schema or weight scaffold is invalid."""

    for theme_key, theme in THEMES.items():
        keys = frozenset(theme)
        if keys != THEME_ENTRY_KEYS:
            missing = sorted(THEME_ENTRY_KEYS - keys)
            extra = sorted(keys - THEME_ENTRY_KEYS)
            raise ValueError(
                f"{theme_key}: schema mismatch; missing={missing}, extra={extra}"
            )

        if theme["family"] not in THEME_FAMILIES:
            raise ValueError(
                f"{theme_key}: unknown family {theme['family']!r}"
            )

        if not isinstance(theme["label"], str) or not theme["label"].strip():
            raise ValueError(f"{theme_key}: label must be non-empty text")

        if not isinstance(theme["notes"], str):
            raise ValueError(f"{theme_key}: notes must be text")

        if not isinstance(theme["default_weight"], Real):
            raise ValueError(f"{theme_key}: default_weight must be numeric")

        for property_name in (
            *WEIGHTED_THEME_PROPERTIES,
            *THEME_METADATA_LIST_PROPERTIES,
        ):
            values = theme[property_name]
            if not isinstance(values, list):
                raise ValueError(
                    f"{theme_key}.{property_name}: expected list"
                )
            if len(values) != len(set(values)):
                raise ValueError(
                    f"{theme_key}.{property_name}: duplicate values are not allowed"
                )

        overrides = theme["weight_overrides"]
        if not isinstance(overrides, dict):
            raise ValueError(f"{theme_key}: weight_overrides must be a dict")

        for property_name, property_overrides in overrides.items():
            if property_name not in WEIGHTED_THEME_PROPERTIES:
                raise ValueError(
                    f"{theme_key}: cannot weight non-membership property "
                    f"{property_name!r}"
                )
            if not isinstance(property_overrides, dict):
                raise ValueError(
                    f"{theme_key}.{property_name}: overrides must be a dict"
                )
            for item, weight in property_overrides.items():
                if item not in theme[property_name]:
                    raise ValueError(
                        f"{theme_key}.{property_name}: override for unlisted "
                        f"item {item!r}"
                    )
                if not isinstance(weight, Real):
                    raise ValueError(
                        f"{theme_key}.{property_name}[{item!r}]: weight must "
                        "be numeric"
                    )


validate_theme_reference()
