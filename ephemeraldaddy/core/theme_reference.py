"""Semantic theme reference for cross-system chart synthesis.

This module is deliberately a routing/indexing layer, not an interpretation
engine. Themes answer "what human subject is this chart factor about?" while
the existing astrology, Human Design, and BaZi engines remain responsible for
calculating and interpreting their own symbols.

Design rules
------------
* THEMES is flat. ``family`` is organizational only and may be changed without
  changing a theme's stable key.
* Labels are presentation text. Stable keys are intended for internal
  references, so labels can be renamed freely.
* Membership is non-exclusive: one symbol may legitimately belong to many
  themes.
* Cross-system mappings are independent. A Human Design gate should earn a
  theme from its Human Design meaning, not merely from its zodiacal position;
  the same principle applies to BaZi.
* Empty lists are meaningful. They mean that no direct correspondence has yet
  been judged defensible, not that a correspondence is forbidden forever.
* Aspects are intentionally absent. They are relational operators/modifiers
  (pressure, flow, polarization, adjustment, etc.), not ordinary thematic
  membership.
* All seed memberships in this file are provisional and expected to evolve.

Weights
-------
Every listed item has an implicit weight of 1.0 unless a future
``weight_overrides`` entry says otherwise. An item not listed for a theme has
weight 0.0 for that theme.
"""

