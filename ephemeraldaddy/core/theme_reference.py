def _theme(
    label: str,
    family: str,
    *,
    signs: list[str] | None = None,
    houses: list[int] | None = None,
    bodies: list[str] | None = None,
    elements: list[str] | None = None,
    modes: list[str] | None = None,
    nakshatras: list[str] | None = None,
    gates: list[int] | None = None,
    channels: list[str] | None = None,
    crosses: list[str] | None = None,
    centers: list[str] | None = None,
    profiles: list[str] | None = None,
    authorities: list[str] | None = None,
    bazisigns: list[str] | None = None,
    color: list[str] | None = None,
    description: list[str] | None = None,
    quotes: list[str] | None = None,
    aliases: list[str] | None = None,
    notes: str = "",
    default_weight: float = DEFAULT_THEME_ITEM_WEIGHT,
    weight_overrides: dict[str, dict[Any, float]] | None = None,
) -> dict[str, Any]:
    """Create one theme entry with the complete, stable schema."""

    return {
        "label": label,
        "family": family,
        "signs": list(signs or []),
        "houses": list(houses or []),
        "bodies": list(bodies or []),
        "elements": list(elements or []),
        "modes": list(modes or []),
        "nakshatras": list(nakshatras or []),
        "gates": list(gates or []),
        "channels": list(channels or []),
        "crosses": list(crosses or []),
        "centers": list(centers or []),
        "profiles": list(profiles or []),
        "authorities": list(authorities or []),
        "bazisigns": list(bazisigns or []),
        "color": list(color or []),
        "description": list(description or []),
        "quotes": list(quotes or []),
        "aliases": list(aliases or []),
        "notes": notes,
        "default_weight": float(default_weight),
        "weight_overrides": {
            property_name: dict(overrides)
            for property_name, overrides in (weight_overrides or {}).items()
        },
    }


